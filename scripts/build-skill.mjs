const header = (from, style = "md") => {
  const text = `Generated by scripts/build-skill.mjs from ${from} in the drawcast repository (${REPO}). Do not edit by hand: rebuild with \`npm run build:skill\`.`;
  if (style === "md") return `<!-- ${text} -->`;
  if (style === "hash") return `# ${text}`;
  return `// ${text}`;
};

/** Replace `from` with `to` in `text`, and fail the build when `from` is not there. */
function must(text, from, to, where) {
  if (!text.includes(from)) throw new Error(`build-skill: ${where} no longer contains ${JSON.stringify(from.slice(0, 80))} — update scripts/build-skill.mjs`);
  return text.split(from).join(to);
}

/** Fail when a generated reference still points into the repo. */
function assertPortable(text, where) {
  const bad = /dev-casts|cast\.mjs|scripts\/cast|src\/llm|src\/scenes|\bgrep\b|_prompt-|references\/(course|revise|publish|pictures)\.md/.exec(text);
  if (bad) throw new Error(`build-skill: ${where} still says "${bad[0]}" — a repo-only instruction`);
}

async function withVite(fn) {
  const server = await createServer({ root: ROOT, server: { middlewareMode: true }, appType: "custom", logLevel: "error" });
  try {
    const { ensureEnabledPacks, PACK_DEFS, DEFAULT_OFF_PACKS } = await server.ssrLoadModule("/src/scenes/packs.ts");
    await ensureEnabledPacks(Object.keys(PACK_DEFS).filter((id) => !DEFAULT_OFF_PACKS.has(id)));
    return await fn((p) => server.ssrLoadModule(p));
  } finally {
    await server.close();
  }
}

const files = new Map();
const put = (path, text) => files.set(path, text.endsWith("\n") ? text : text + "\n");
const src = (p) => readFileSync(resolve(ROOT, p), "utf8");

// ---- rule card ---------------------------------------------------------------

function ruleCard() {
  const from = ".claude/skills/drawcast/references/rule-card.md";
  let t = src(from);
  const start = t.indexOf("## The page");
  if (start === -1) throw new Error(`build-skill: ${from} has no "## The page"`);
  const intro = [
    "# The compiler's rules, short (the rule card)",
    "",
    "Every tool fact the renderer depends on, in one line where one line will do,",
    "and the house taste as single lines. The teaching craft (question, insight,",
    "example, one change at a time, quiz) is the storyline's job",
    "(`storyline.md`); this card is how to STAGE it. The examples below are",
    "written as JSON objects (`{\"draw\": [\"eq\"]}`); in your YAML they are the same",
    "keys and values (`draw: [eq]`). When a field's exact shape matters, search",
    "`schema.json`; when a verb's behaviour matters, search `compiler.md`.",
    "",
    "",
  ].join("\n");
  t = intro + t.slice(start);
  t = must(t, "user gave (`url`, `look: \"screen\"`, `regions` — see references/pictures.md).", "user gave (`url`, `look: \"screen\"`, `regions` as boxes you can see — never `regions: auto`).", from);
  const sound = t.indexOf("## Sound and code");
  if (sound === -1) throw new Error(`build-skill: ${from} has no "## Sound and code"`);
  const tail = t.slice(t.indexOf("These are defaults, not laws", sound));
  t = t.slice(0, sound) + [
    "## Sound and code",
    "",
    "A drawcast about music or sound: read `sound.md` (the `play` verb, the",
    "`music` element). One that runs a script, a simulation or shows code: read",
    "`code.md` in full.",
    "",
    tail,
  ].join("\n");
  assertPortable(t, "rule-card.md");
  return `${header(from)}\n\n${t}`;
}

// ---- storyline ---------------------------------------------------------------

function storyline(treatment) {
  const from = "src/llm/prompts/treatment-v3.md and stagingNote() in src/llm/treatment.ts";
  let t = treatment.STORYLINE_PROMPT_SOURCE;
  t = must(t, "A ready template (listed below)", "A ready template (`templates/index.md`)", "treatment-v3.md");
  t = must(t, "If a template\n    in the library index (not shortlisted) would fit better, name it; its full\n    entry will be fetched.", "Read the\n    chosen template's own file (`templates/<id>.md`) before you plan beats\n    around it.", "treatment-v3.md");
  t = must(t, "Figures: ready templates (below)", "Figures: ready templates (`templates/index.md`)", "treatment-v3.md");
  const staging = treatment
    .stagingNote("", "v3")
    .split("\n")
    .filter((line) => !line.includes(treatment.TEMPLATE_GAPS_KEY))
    .map((line) => line.replace(/^## The storyline to stage$/, "## Then stage it"))
    .map((line) => line.replace("A teacher has already written this drawcast's storyline. STAGE it:", "With the storyline written, STAGE it as YAML:"))
    .map((line) => line.replace(", following your instructions;", ", following `rule-card.md`;"))
    .join("\n")
    .trim();
  const preface = [
    "In this skill you do both steps yourself: first the storyline, by the rules",
    "below (\"the next step\" is you, writing the YAML), then the staging, by the",
    "last section. Write the storyline in plain text in your working notes.",
    "",
    "",
  ].join("\n");
  const firstBreak = t.indexOf("\n\n");
  t = `${t.slice(0, firstBreak)}\n\n${preface}${t.slice(firstBreak + 2).trim()}\n\n${staging}`;
  assertPortable(t, "storyline.md");
  return `${header(from)}\n\n${t}`;
}

// ---- look --------------------------------------------------------------------

function look(compile) {
  const from = "src/llm/prompts/look-v1.md and PEDAGOGY_RUBRIC in src/llm/compile.ts";
  const lookMd = src("src/llm/prompts/look-v1.md");
  const bullets = lookMd.slice(lookMd.indexOf("- **Legibility:**"), lookMd.indexOf("House style:")).trim();
  const houseStyle = lookMd.slice(lookMd.indexOf("House style:"), lookMd.indexOf("Answer in plain text:")).trim();
  const rubric = compile.PEDAGOGY_RUBRIC.split("\n").filter((l) => /^\d+\./.test(l)).join("\n");
  if (!bullets || !houseStyle || !rubric) throw new Error("build-skill: look-v1.md or PEDAGOGY_RUBRIC changed shape");
  const t = [
    "# Self-check: look and teaching",
    "",
    "The app's reviewers read a finished drawcast against these two lists. You",
    "cannot see the frames: walk the YAML beat by beat and picture the page as",
    "it looks while each line is spoken (the canvas is 1000 × 750, 4:3). If the",
    "user sends a screenshot of the player, judge it by the first list.",
    "",
    "## How it looks (the visual reviewer's list)",
    "",
    bullets,
    "",
    houseStyle,
    "",
    "Fixes change the drawing and the staging, not the spoken lines, unless a",
    "line contradicts the picture. \"Remove X\" (or \"erase X after beat N\") is",
    "often the best fix.",
    "",
    "## How it teaches (the teacher's list)",
    "",
    rubric,
  ].join("\n");
  assertPortable(t, "look.md");
  return `${header(from)}\n\n${t}`;
}

// ---- the compiler prompt, sound, code ---------------------------------------------

function compilerRef(compile) {
  const from = "src/llm/prompts/compiler-v1.md";
  let t = compile.promptVariants().find((v) => v.name === "v1")?.source;
  if (!t) throw new Error("build-skill: no compiler-v1 prompt");
  t = t.slice(0, t.indexOf("## Output"));
  t = must(t, "{{SOUND}}", "(The `play` verb and the `music` element: `sound.md`.)", from);
  t = must(t, "{{CODE}}", "- **code** (a script that runs and draws its output): `code.md`.", from);
  t = must(
    t,
    "the app maps a picture URL in the request for you: use the part names it lists (write `\"regions\": \"auto\"` on the image; the boxes are filled in); without a list, only boxes the user gave",
    "nothing maps the picture for you here: write boxes only for parts you can see in it yourself, or boxes the user gave, and never `\"regions\": \"auto\"`",
    from,
  );
  t = must(t, "Only the output contract is absolute: a valid spec, JSON only.", "Only the output contract is absolute: a valid spec.", from);
  const preface = [
    "<!-- The app's full compiler prompt, for looking a verb or an element up.",
    "     Written for the app's one-shot generator: where it says JSON, write the",
    "     same keys and values as YAML; its schema is schema.json, its catalogue",
    "     templates/, and its examples are examples/. -->",
  ].join("\n");
  assertPortable(t, "compiler.md");
  return `${header(from)}\n${preface}\n\n${t.trim()}`;
}

