// ---- brief -------------------------------------------------------------------------

function briefLines(briefControls) {
  const defaults = { audience: "curious adults of better-than-average ability with decent general knowledge, but no special knowledge of this topic", level: "standard", length: "14–20 spoken lines" };
  return briefControls.BRIEF_CONTROLS.map((c) => {
    const def = c.options.find((o) => o.value === "");
    const others = c.options.filter((o) => o.value && o.value !== "for").map((o) => `\`#${o.value}\` ${o.label.toLowerCase()} (${o.hint.replace(/^./, (x) => x.toLowerCase())})`);
    if (c.options.some((o) => o.value === "for")) others.push("`#for=<who>` anyone else (`#for=nurses`)");
    const d = c.group === "level" ? `\`standard\` — ${def.hint.replace(/^./, (x) => x.toLowerCase())}` : c.group === "length" ? def.hint : defaults.audience;
    return `- **${c.label}:** ${d}. Others: ${others.join("; ")}.`;
  }).join("\n");
}

function briefRef(tags) {
  const from = "src/llm/tags.ts";
  const groups = new Map();
  for (const def of tags.TAGS) {
    if (!groups.has(def.group)) groups.set(def.group, []);
    groups.get(def.group).push(def);
  }
  const lines = [
    "# The request's tags",
    "",
    "The app's request box understands these hashtags; a user may type them in a",
    "request to you too, or say the same in words. Each tag adds the brief shown",
    "under it to your instructions. Tags in one group exclude each other (the",
    "last one wins). A tag that asks for something the rest of this skill does",
    "not cover (a playlist of several parts) — do the nearest single drawcast and",
    "say so.",
    "",
  ];
  for (const [group, defs] of groups) {
    lines.push(`## ${group}`, "");
    for (const d of defs) {
      const names = [d.tag, ...(d.aliases ?? [])].map((n) => `\`#${n}\``).join(", ");
      lines.push(`- ${names} — ${d.hint}${d.brief ? `\n  ${d.brief}` : ""}`);
    }
    lines.push("");
  }
  lines.push(`Shared by the reality tags: ${tags.GUARDRAIL}`, "", `Shared by the tone tags: ${tags.RESTRAINT}`);
  return `${header(from)}\n\n${lines.join("\n")}`;
}

// ---- templates ---------------------------------------------------------------------

function firstSentence(d) {
  const m = /^[^.!?]*[.!?]/.exec(d.trim());
  return (m ? m[0] : d.trim()).trim();
}
function chooseSentence(d) {
  const m = /\b(?:Choose|Use|Pick) this[^.!?]*[.!?]/.exec(d);
  return m ? m[0].trim() : null;
}

function templates(catalog, scenes, packs) {
  const ready = Object.values(scenes).filter((s) => s.manifest.status === "ready" && catalog.isReadyTemplate(s.manifest.name));
  const index = [
    header("the scene registry (src/scenes, catalogParts in src/scenes/catalog.ts)"),
    "",
    "# The templates",
    "",
    `${ready.length} ready templates. A template draws an exact, good-looking figure from a few`,
    "`params` and names its parts, so your commands can draw, highlight and",
    "animate them. Use one when it can tell THIS story (`template: <id>` +",
    "`params:`); otherwise build the figure freehand from elements (`rule-card.md`).",
    "Before using one, read its own file, `templates/<id>.md`: its parameter",
    "schema, its element ids, and example params. \"Viewer can\" is what the viewer",
    "can do with it while paused — plan an explore beat around it.",
    "",
  ];
  // Grouped by field (the app's packs), the built-in templates first.
  const byId = new Map(ready.map((s) => [s.manifest.name, s.manifest]));
  const groups = [];
  const packed = new Set();
  for (const def of Object.values(packs.PACK_DEFS)) {
    const ids = packs.packTemplateIds(def.id).filter((id) => byId.has(id) && !packed.has(id));
    ids.forEach((id) => packed.add(id));
    if (ids.length) groups.push({ title: def.title, ids });
  }
  groups.unshift({ title: "General", ids: [...byId.keys()].filter((id) => !packed.has(id)) });
  const out = {};
  for (const g of groups) {
    index.push(`## ${g.title}`, "");
    for (const id of g.ids) {
      const m = byId.get(id);
      const choose = chooseSentence(m.description);
      const first = firstSentence(m.description);
      index.push(`- **${m.name}**: ${first}${choose && choose !== first ? ` ${choose}` : ""}${m.interaction ? `\n  Viewer can: ${m.interaction}` : ""}`);
    }
    index.push("");
  }
  for (const { manifest: m } of ready) {    let entry = catalog.catalogParts({ forced: m.name }).stable;
    entry = must(entry, `\n\nYou MUST set "template" to "${m.name}" for this request.`, "", `the catalog entry of ${m.name}`);
    entry = entry.replace(/^### Scene template: (\S+) \(READY — prefer this when it fits\)/, "# Template: $1");
    const lines = [
      header(`the ${m.name} manifest (catalogParts in src/scenes/catalog.ts)`),
      "",
      entry.trim(),
    ];
    if (m.interaction) lines.push("", `Viewer can: ${m.interaction}`);
    lines.push("", `In YAML: \`template: ${m.name}\` and \`params:\` per the schema above; commands name the element ids above.`);
    out[m.name] = lines.join("\n");
  }
  return { index: index.join("\n"), entries: out, count: ready.length };
}

// ---- examples ----------------------------------------------------------------------

function examples(text, validate) {
  const all = JSON.parse(src("src/examples.json"));
  const out = [];
  for (const ex of EXAMPLES) {
    const found = all.filter((e) => !e.specimen && e.spec && e.request.startsWith(ex.request));
    if (found.length !== 1) throw new Error(`build-skill: example "${ex.request}" matches ${found.length} entries of src/examples.json`);
    const { spec, request } = found[0];
    const v = validate(spec);
    if (!v.ok) throw new Error(`build-skill: example ${ex.name} is invalid: ${v.errors.join("; ")}`);
    const yaml = text.dumpSpecYaml(spec);
    const body = [
      header("src/examples.json", "hash"),
      `# Request: ${request.replace(/\s+/g, " ")}`,
      `# Shows: ${ex.kind.replace(/`/g, "")}`,
      yaml,
    ].join("\n");
    out.push({ ...ex, file: `${ex.name}.yaml`, body });
  }
  return out;
}

// ---- SKILL.md ---------------------------------------------------------------------

function skillMd({ brief, count, exampleRows }) {
  let t = src("scripts/skill/SKILL.md");
  const skeleton = src("scripts/skill/skeleton.yaml").trimEnd();
  t = must(t, "{{HEADER}}", header("scripts/skill/SKILL.md"), "SKILL.md");
  t = must(t, "{{BRIEF}}", brief, "SKILL.md");
  t = must(t, "{{TEMPLATE_COUNT}}", String(count), "SKILL.md");
  t = must(t, "{{EXAMPLES}}", exampleRows, "SKILL.md");
  t = must(t, "{{SKELETON}}", skeleton, "SKILL.md");
  if (/\{\{[A-Z_]+\}\}/.test(t)) throw new Error("build-skill: SKILL.md has an unfilled placeholder");
  assertPortable(t, "SKILL.md");
  return t;
}

function linkScript(name, style) {
  const from = `scripts/skill/${name}`;
  const t = src(from);
  const nl = t.indexOf("\n");
  // The shebang stays first; the generated note follows it.
  return `${t.slice(0, nl)}\n${header(from, style)}\n${t.slice(nl + 1)}`;
}

// ---- build ------------------------------------------------------------------------

export async function buildSkill() {
  await withVite(async (load) => {
    const compile = await load("/src/llm/compile.ts");
    const catalog = await load("/src/scenes/catalog.ts");
    const { scenes } = await load("/src/scenes/registry.ts");
    const treatment = await load("/src/llm/treatment.ts");
    const tags = await load("/src/llm/tags.ts");
    const briefControls = await load("/src/llm/brief-controls.ts");
    const text = await load("/src/spec/text.ts");
    const { validateSpec } = await load("/src/spec/schema.ts");

    const tpl = templates(catalog, scenes, await load("/src/scenes/packs.ts"));
    const exs = examples(text, validateSpec);
    const exampleRows = ["| File | Request | Shows |", "|---|---|---|", ...exs.map((e) => `| \`references/examples/${e.file}\` | ${e.request.replace(/\|/g, "/")}${e.request.endsWith("?") ? "" : "…"} | ${e.kind} |`)].join("\n");

    put("SKILL.md", skillMd({ brief: briefLines(briefControls), count: tpl.count, exampleRows }));
    put("references/rule-card.md", ruleCard());
    put("references/storyline.md", storyline(treatment));
    put("references/look.md", look(compile));
    put("references/compiler.md", compilerRef(compile));
    put("references/sound.md", soundRef(compile));
    put("references/code.md", codeRef(compile));
    put("references/brief.md", briefRef(tags));
    // The full schema (code and sound included): the file is read on demand,
    // so there is no prompt budget to gate it for.
    put("references/schema.json", JSON.stringify(compile.apiSchema(), null, 1));
    put("references/templates/index.md", tpl.index);
    for (const [id, body] of Object.entries(tpl.entries)) put(`references/templates/${id}.md`, body);
    for (const e of exs) put(`references/examples/${e.file}`, e.body);
    put("scripts/make_link.py", linkScript("make_link.py", "hash"));
    put("scripts/make_link.mjs", linkScript("make_link.mjs", "slash"));
  });

  rmSync(OUT, { recursive: true, force: true });
  for (const [path, body] of files) {
    const at = join(OUT, path);
    mkdirSync(dirname(at), { recursive: true });
    writeFileSync(at, body);
  }
  chmodSync(join(OUT, "scripts/make_link.py"), 0o755);
  chmodSync(join(OUT, "scripts/make_link.mjs"), 0o755);

  // The zip holds the folder itself (drawcast/SKILL.md …), the layout a skill upload expects.
  const zip = join(DIST, "drawcast-skill.zip");
  rmSync(zip, { force: true });
  const r = spawnSync("zip", ["-qrX", zip, "drawcast"], { cwd: DIST, stdio: "inherit" });
  if (r.status !== 0) throw new Error("build-skill: zip failed (is the zip command installed?)");
  return { out: OUT, zip, files: [...files.keys()] };
}

function tree(dir) {
  const rows = [];
  const walk = (d) => {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else rows.push(`${String(statSync(p).size).padStart(8)}  ${relative(dir, p)}`);
    }
  };
  walk(dir);
  return rows;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { out, zip, files: list } = await buildSkill();
  const rows = tree(out);
  const templatesCount = list.filter((f) => f.startsWith("references/templates/") && !f.endsWith("index.md")).length;
  console.log(rows.filter((r) => !/references\/templates\/(?!index)/.test(r)).join("\n"));
  console.log(`   (+ ${templatesCount} files references/templates/<id>.md)`);
  console.log(`${relative(ROOT, out)}: ${list.length} files · ${relative(ROOT, zip)}: ${statSync(zip).size} bytes`);
}
